export const DEFAULT_LIU_GEN_PAO_PAUSE_SECONDS = 0.0;

/**
 * Шаг численного интегрирования дифференциальных уравнений по умолчанию (секунды).
 *
 * Анализ численной устойчивости:
 * Метод Хойна (двухстадийный явный метод Рунге-Кутты 2-го порядка) условно устойчив.
 * Условие устойчивости схемы для линейной системы ОДУ теплопроводности требует |λ_max * dt| < 2,
 * то есть dt < 2 * τ_min, где τ_min = min(C / G) — минимальная постоянная времени системы.
 * При типичных параметрах заваривания чая (V >= 20 мл, масса сосуда >= 50 г, проводимости G <= 5 Вт/К)
 * наименьшая постоянная времени составляет τ_min ≈ 15–25 с.
 * Шаг dt = 0.1 с даёт безразмерный параметр dt / τ <= 0.007 << 2, гарантируя высокую точность O(dt^2)
 * и устойчивость без численных осцилляций.
 */
export const DEFAULT_INTEGRATOR_TIME_STEP_SECONDS = 0.1;
